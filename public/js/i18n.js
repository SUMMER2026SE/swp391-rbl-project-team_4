function changeLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('dcinema_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (element.tagName === 'INPUT' && element.hasAttribute('placeholder')) {
                element.placeholder = translations[lang][key];
            } else {
                element.innerHTML = translations[lang][key];
            }
        }
    });

    // Cập nhật lại Text cho node text mà có icon kế bên nếu có
    // Dành cho nút có icon con bên trong (như nút 'Phim' có mũi tên)
    const navMovies = document.getElementById('nav-phim');
    if (navMovies) {
        navMovies.innerHTML = translations[lang]['nav_movies'] + ' <span class="nav-arrow">▾</span>';
    }
    
    // AI Title có icon
    const aiTitle = document.querySelector('.ai-header h2');
    if (aiTitle) {
        aiTitle.innerHTML = `
            <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
                <path d="m12 3-1.912 5.813a2 2 0 0 1-1.275 1.275L3 12l5.813 1.912a2 2 0 0 1 1.275 1.275L12 21l1.912-5.813a2 2 0 0 1 1.275-1.275L21 12l-5.813-1.912a2 2 0 0 1-1.275-1.275L12 3Z" />
            </svg>
            ${translations[lang]['ai_title']}
        `;
    }

    // Chọn đúng option trong dropdown switcher
    const switcher = document.getElementById('langSwitcher');
    if (switcher) {
        switcher.value = lang;
    }
}

// Khởi tạo ngôn ngữ khi tải trang
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('dcinema_lang') || 'vi';
    changeLanguage(savedLang);
});
